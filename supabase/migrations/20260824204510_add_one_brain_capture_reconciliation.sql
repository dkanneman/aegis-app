create or replace function private.pepper_assert_jsonb_keys(
  value_input jsonb,
  allowed_keys_input text[],
  context_input text
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  unexpected_key text;
begin
  if value_input is null or pg_catalog.jsonb_typeof(value_input) <> 'object' then
    raise exception '% must be a JSON object.', context_input using errcode = '22023';
  end if;

  select key into unexpected_key
  from pg_catalog.jsonb_object_keys(value_input) as keys(key)
  where not (key = any(allowed_keys_input))
  order by key
  limit 1;

  if unexpected_key is not null then
    raise exception 'Unexpected key "%" in %.', unexpected_key, context_input using errcode = '22023';
  end if;
end;
$$;

create or replace function private.pepper_assert_household_member(
  household_id_input uuid,
  member_id_input uuid,
  context_input text
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if member_id_input is not null and not exists (
    select 1
    from public.household_members hm
    where hm.id = member_id_input
      and hm.household_id = household_id_input
  ) then
    raise exception '% is not a member of this household.', context_input using errcode = '23503';
  end if;
end;
$$;

create or replace function private.pepper_stamp_state_change_context()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  context_capture_id uuid;
  context_actor_id uuid;
begin
  context_capture_id := nullif(pg_catalog.current_setting('pepper.capture_id', true), '')::uuid;
  context_actor_id := nullif(pg_catalog.current_setting('pepper.actor_member_id', true), '')::uuid;

  new.capture_id := coalesce(new.capture_id, context_capture_id);
  new.actor_member_id := coalesce(new.actor_member_id, context_actor_id);

  if new.capture_id is not null and not exists (
    select 1 from public.captures c
    where c.id = new.capture_id and c.household_id = new.household_id
  ) then
    raise exception 'State change capture does not belong to the household.' using errcode = '23503';
  end if;
  perform private.pepper_assert_household_member(new.household_id, new.actor_member_id, 'State change actor');
  return new;
end;
$$;

