-- V6 Phase 1: One Brain capture reconciliation foundation.
--
-- Captures remain append-first input history. Canonical writes are applied only
-- through private.apply_capture_plan(), in one database transaction, with an
-- idempotency ledger and capture/actor trace context for downstream triggers.

alter table public.captures
  add column if not exists sharing_scope text not null default 'member_private',
  add column if not exists remaining_ambiguities jsonb not null default '[]'::jsonb,
  add column if not exists reconciled_by_member_id uuid references public.household_members(id) on delete set null,
  add column if not exists reconciled_at timestamptz,
  add column if not exists reconciliation_version integer;

alter table public.captures
  drop constraint if exists captures_sharing_scope_check,
  add constraint captures_sharing_scope_check
    check (sharing_scope in ('member_private', 'household')),
  drop constraint if exists captures_remaining_ambiguities_array_check,
  add constraint captures_remaining_ambiguities_array_check
    check (jsonb_typeof(remaining_ambiguities) = 'array'),
  drop constraint if exists captures_aegis_record_ids_array_check,
  add constraint captures_aegis_record_ids_array_check
    check (aegis_record_ids is null or jsonb_typeof(aegis_record_ids) = 'array');

-- "pending" was ambiguous: it could mean untouched, failed, or waiting for a
-- person. Preserve that history without claiming that any canonical write was
-- applied. Existing review rows remain reviewable; all other pending rows return
-- to the explicit captured state.
alter table public.captures drop constraint if exists captures_aegis_sync_status_check;

update public.captures
set aegis_sync_status = case
      when status in ('partially_applied', 'needs_review') then 'needs_review'
      when status = 'dismissed' then 'not_applicable'
      else 'captured'
    end,
    aegis_record_ids = coalesce(aegis_record_ids, '[]'::jsonb)
where aegis_sync_status = 'pending'
   or aegis_sync_status is null
   or aegis_record_ids is null;

alter table public.captures
  alter column aegis_sync_status set default 'captured',
  alter column aegis_record_ids set default '[]'::jsonb,
  add constraint captures_aegis_sync_status_check
    check (aegis_sync_status in ('captured', 'synced', 'needs_review', 'failed', 'not_applicable'));

drop index if exists public.captures_aegis_pending_idx;
create index if not exists captures_reconciliation_queue_idx
  on public.captures (member_id, captured_at desc)
  where aegis_sync_status in ('captured', 'needs_review', 'failed');

comment on column public.captures.sharing_scope is
  'Privacy of the raw capture. member_private is the default; household requires explicit capture semantics.';
comment on column public.captures.remaining_ambiguities is
  'Explicit unresolved portions of a capture. Pepper must not invent writes to empty this list.';
comment on column public.captures.aegis_sync_status is
  'Canonical reconciliation state. captured is new/unapplied; synced is fully applied; needs_review is explicit; failed is retryable; not_applicable is reviewed with no canonical write.';

create or replace function private.pepper_preserve_capture_input()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.household_id is distinct from old.household_id
     or new.member_id is distinct from old.member_id
     or new.source is distinct from old.source
     or new.original_text is distinct from old.original_text
     or new.captured_at is distinct from old.captured_at
     or new.dedupe_key is distinct from old.dedupe_key then
    raise exception 'Original capture input is immutable.' using errcode = '55000';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_pepper_preserve_capture_input on public.captures;
create trigger trg_pepper_preserve_capture_input
before update on public.captures
for each row execute function private.pepper_preserve_capture_input();

revoke execute on function private.pepper_preserve_capture_input() from public, anon, authenticated, service_role;

