  capture_id_input uuid,
  actor_member_id_input uuid,
  error_input text
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  update public.captures c
  set aegis_sync_status = 'failed',
      aegis_last_attempt_at = now(),
      aegis_sync_error = left(coalesce(error_input, 'Capture plan failed.'), 1000),
      updated_at = now()
  where c.id = capture_id_input
    and c.member_id = actor_member_id_input
    and c.status in ('captured','partially_applied','needs_review');
  if not found then
    raise exception 'Capture not found or not retryable.' using errcode = '42501';
  end if;
end;
$$;
revoke execute on function private.pepper_record_capture_apply_failure(uuid,uuid,text) from public, anon, authenticated, service_role;

