create or replace function private.pepper_record_ref_exists(
  household_id_input uuid,
  entity_type_input text,
  record_id_input uuid
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  return case entity_type_input
    when 'task' then exists(select 1 from public.tasks t where t.id=record_id_input and t.household_id=household_id_input)
    when 'event' then exists(select 1 from public.events e where e.id=record_id_input and e.household_id=household_id_input)
    when 'grocery' then exists(select 1 from public.groceries g where g.id=record_id_input and g.household_id=household_id_input)
    when 'meal' then exists(select 1 from public.meal_plan m where m.id=record_id_input and m.household_id=household_id_input)
    when 'responsibility' then exists(select 1 from public.responsibilities r where r.id=record_id_input and r.household_id=household_id_input)
    when 'decision' then exists(select 1 from public.decisions d where d.id=record_id_input and d.household_id=household_id_input)
    else false
  end;
end;
$$;
revoke execute on function private.pepper_record_ref_exists(uuid,text,uuid) from public, anon, authenticated, service_role;

create or replace function private.capture_backlog_dry_run(
  expected_capture_ids_input uuid[],
  expected_capture_count_input integer,
  expected_record_refs_input jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  actual_capture_ids uuid[];
  actual_count integer;
  expected_count integer;
  ref_value jsonb;
  capture_id_value uuid;
  record_id_value uuid;
  entity_type_value text;
  household_id_value uuid;
  actual_refs jsonb;
  expected_refs jsonb;
begin
  if expected_capture_ids_input is null
     or expected_capture_count_input is null
     or expected_record_refs_input is null
     or pg_catalog.jsonb_typeof(expected_record_refs_input) <> 'array' then
    raise exception 'Expected capture IDs, count, and record references are required.' using errcode = '22023';
  end if;

  select coalesce(array_agg(c.id order by c.id), array[]::uuid[]), count(*)::integer
  into actual_capture_ids, actual_count
  from public.captures c
  where c.status <> 'dismissed'
    and c.aegis_sync_status in ('captured','needs_review','failed');

  select count(distinct id)::integer into expected_count
  from unnest(expected_capture_ids_input) ids(id);
  if expected_count <> cardinality(expected_capture_ids_input)
     or expected_capture_count_input <> expected_count
     or actual_count <> expected_capture_count_input
     or actual_capture_ids is distinct from (
       select coalesce(array_agg(id order by id), array[]::uuid[])
       from unnest(expected_capture_ids_input) ids(id)
     ) then
    raise exception 'Backlog capture IDs or count changed; regenerate the dry-run manifest.' using errcode = 'P0003';
  end if;

  for ref_value in select value from pg_catalog.jsonb_array_elements(expected_record_refs_input)
  loop
    perform private.pepper_assert_jsonb_keys(ref_value, array['capture_id','entity_type','record_id'], 'backlog record reference');
    capture_id_value := nullif(ref_value->>'capture_id','')::uuid;
    record_id_value := nullif(ref_value->>'record_id','')::uuid;
    entity_type_value := ref_value->>'entity_type';
    if capture_id_value is null or record_id_value is null
       or entity_type_value not in ('task','event','grocery','meal','responsibility','decision') then
      raise exception 'Unexpected backlog record reference.' using errcode = '22023';
    end if;
    select c.household_id into household_id_value
    from public.captures c
    where c.id = capture_id_value and c.id = any(expected_capture_ids_input);
    if not found
       or not private.pepper_record_ref_exists(household_id_value, entity_type_value, record_id_value) then
      raise exception 'Backlog record reference is missing or outside the capture household.' using errcode = 'P0003';
    end if;
  end loop;

  select coalesce(pg_catalog.jsonb_agg(ref order by ref::text), '[]'::jsonb)
  into expected_refs
  from (select distinct value as ref from pg_catalog.jsonb_array_elements(expected_record_refs_input)) refs;

  select coalesce(pg_catalog.jsonb_agg(ref order by ref::text), '[]'::jsonb)
  into actual_refs
  from (
    select distinct pg_catalog.jsonb_build_object(
      'capture_id', c.id,
      'entity_type', ref->>'entity_type',
      'record_id', ref->>'record_id'
    ) as ref
    from public.captures c
    cross join lateral pg_catalog.jsonb_array_elements(coalesce(c.aegis_record_ids, '[]'::jsonb)) refs(ref)
    where c.id = any(expected_capture_ids_input)
  ) refs;

  if actual_refs is distinct from expected_refs then
    raise exception 'Backlog canonical record references changed; regenerate the dry-run manifest.' using errcode = 'P0003';
  end if;

  return pg_catalog.jsonb_build_object(
    'ok', true,
    'dry_run', true,
    'capture_count', actual_count,
    'capture_ids', to_jsonb(actual_capture_ids),
    'record_refs', actual_refs,
    'writes_applied', 0
  );
end;
$$;
revoke execute on function private.capture_backlog_dry_run(uuid[],integer,jsonb) from public, anon, authenticated, service_role;

-- Keep the existing public capture helpers response-compatible while removing
-- pending and preventing non-transactional "applied" finalization.
create or replace function public.pepper_capture_input(
  session_token_input uuid,
  source_input text,
  original_text_input text,
  dedupe_key_input text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_member uuid;
  current_household uuid;
  capture_id_value uuid;
  source_value text;
  original_text_value text;
  dedupe_key_value text;
  captured_at_value timestamptz;
begin
  current_member := private.pepper_set_session(session_token_input);
  current_household := private.pepper_current_household_id();
  perform private.pepper_touch_session(session_token_input);
  source_value := case lower(btrim(coalesce(source_input, 'text'))) when 'voice' then 'voice' else 'text' end;
  original_text_value := btrim(coalesce(original_text_input, ''));
  dedupe_key_value := left(nullif(btrim(coalesce(dedupe_key_input, '')), ''), 200);
  if original_text_value = '' or length(original_text_value) > 4000 then
    raise exception 'Tell Pepper something under 4,000 characters to save.' using errcode = '22023';
  end if;

  insert into public.captures(
    household_id, member_id, source, original_text, status, extracted_facts,
    applied_changes, dedupe_key, aegis_sync_status, sharing_scope
  ) values (
    current_household, current_member, source_value, original_text_value, 'captured',
    '[]'::jsonb, '[]'::jsonb, dedupe_key_value, 'captured', 'member_private'
  )
  on conflict (household_id, dedupe_key) where dedupe_key is not null do nothing
  returning id, captured_at into capture_id_value, captured_at_value;

  if capture_id_value is null and dedupe_key_value is not null then
    select c.id, c.captured_at into capture_id_value, captured_at_value
    from public.captures c
    where c.household_id=current_household and c.member_id=current_member and c.dedupe_key=dedupe_key_value;
  end if;
  if capture_id_value is null then raise exception 'Pepper could not preserve that note.' using errcode='P0001'; end if;
  return pg_catalog.jsonb_build_object(
    'ok',true,'capture_id',capture_id_value,'status','captured',
    'aegis_sync_status','captured','captured_at',captured_at_value
  );
end;
$$;

create or replace function public.pepper_finalize_capture(
  session_token_input uuid,
  capture_id_input uuid,
  status_input text,
  extracted_facts_input jsonb default '[]'::jsonb,
  applied_changes_input jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_member uuid;
  current_household uuid;
begin
  current_member := private.pepper_set_session(session_token_input);
  current_household := private.pepper_current_household_id();
  perform private.pepper_touch_session(session_token_input);
  if lower(btrim(coalesce(status_input,''))) <> 'needs_review'
     or pg_catalog.jsonb_typeof(coalesce(extracted_facts_input,'[]'::jsonb)) <> 'array'
     or pg_catalog.jsonb_typeof(coalesce(applied_changes_input,'[]'::jsonb)) <> 'array'
     or pg_catalog.jsonb_array_length(coalesce(applied_changes_input,'[]'::jsonb)) <> 0 then
    raise exception 'Canonical changes must be finalized through apply_capture_plan.' using errcode='22023';
  end if;
  update public.captures c set
    status='needs_review', extracted_facts=coalesce(extracted_facts_input,'[]'::jsonb),
    applied_changes='[]'::jsonb,
    remaining_ambiguities=case
      when pg_catalog.jsonb_array_length(coalesce(extracted_facts_input,'[]'::jsonb)) > 0
        then extracted_facts_input
      else pg_catalog.jsonb_build_array('Legacy capture requires review')
    end,
    aegis_sync_status='needs_review', aegis_last_attempt_at=now(), updated_at=now()
  where c.id=capture_id_input and c.household_id=current_household and c.member_id=current_member and c.status='captured';
  if not found then raise exception 'Capture not found or not permitted.' using errcode='42501'; end if;
  return pg_catalog.jsonb_build_object(
    'ok',true,'capture_id',capture_id_input,'status','needs_review','aegis_sync_status','needs_review'
  );
end;
$$;

drop policy if exists captures_member_insert on public.captures;
create policy captures_member_insert
on public.captures for insert to anon, authenticated
with check (
  household_id = (select private.pepper_current_household_id())
  and member_id = (select private.pepper_current_member_id())
  and source in ('voice','text')
  and status = 'captured'
  and aegis_sync_status = 'captured'
  and sharing_scope = 'member_private'
);

revoke execute on function public.pepper_capture_input(uuid,text,text,text) from public;
revoke execute on function public.pepper_finalize_capture(uuid,uuid,text,jsonb,jsonb) from public;
grant execute on function public.pepper_capture_input(uuid,text,text,text) to anon, authenticated;
