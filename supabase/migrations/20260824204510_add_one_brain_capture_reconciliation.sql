  original_text text,
  source text,
  status text,
  reconciliation_status text,
  extracted_facts jsonb,
  applied_changes jsonb,
  remaining_ambiguities jsonb,
  canonical_records jsonb,
  captured_at timestamptz,
  updated_at timestamptz
