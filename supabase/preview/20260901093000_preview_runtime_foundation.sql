create or replace function private.pepper_set_session(session_token_input uuid)
returns uuid
language plpgsql
set search_path to public, private, pg_temp
as $$
declare
  member_result uuid;
begin
  perform set_config('app.pepper_session_token', session_token_input::text, true);
  member_result := private.pepper_current_member_id();
  if member_result is null then
    raise exception 'Pepper session expired. Please unlock Pepper again.' using errcode = '28000';
  end if;
  return member_result;
end;
$$;

