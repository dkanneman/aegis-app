create or replace function private.pepper_current_member_id()
returns uuid
language plpgsql
stable
security definer
set search_path to public, private, pg_temp
as $$
declare
  token_text text;
  member_result uuid;
begin
  token_text := current_setting('app.pepper_session_token', true);
  if token_text is null
     or token_text !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    return null;
  end if;

  select s.member_id into member_result
  from public.member_sessions s
  where s.token = token_text::uuid
    and s.revoked_at is null
    and s.expires_at > now()
  limit 1;

  return member_result;
end;
$$;

